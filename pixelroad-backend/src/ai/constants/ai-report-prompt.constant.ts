// 사용자 데이터를 넣는 prompt함수
export function createAiReportPrompt(
  visitedLandmarks: unknown[], recommendation: unknown
): string {
  return `
    [사용자 방문 기록]
    ${JSON.stringify(visitedLandmarks, null, 2)}
    [백엔드가 선정한 추천 랜드마크]
    ${JSON.stringify(recommendation, null, 2)}

   위 데이터를 기반으로
    1. 탐험 성향 분석
    2. 추천 이유

    를 작성하세요.
    `.trim();
}